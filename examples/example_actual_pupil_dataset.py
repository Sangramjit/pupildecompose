import pandas as pd

from pupildecompose import run_decompose


# =====================================================
# ---------------- LOAD DATASET -----------------------
# =====================================================

df = pd.read_csv(

    "E:\Research\My_Tools\pupildecompose\examples\pupil_dataset.csv"
)

print("\nDataset loaded.\n")

print(df.head())


# =====================================================
# ---------------- RUN PIPELINE -----------------------
# =====================================================

results = run_decompose(

    df,

    # -------------------------------------------------
    # dataframe structure
    # -------------------------------------------------

    participant_col=0,

    condition_col=1,

    pupil_start_col=89,

    # -------------------------------------------------
    # analysis mode
    # -------------------------------------------------

    mode="trial",

    # -------------------------------------------------
    # preprocessing
    # -------------------------------------------------

    preprocess=False,

    # -------------------------------------------------
    # acquisition
    # -------------------------------------------------

    sample_interval_ms=(1000 / 120),

    # -------------------------------------------------
    # baseline
    # -------------------------------------------------

    baseline_window=(0, 20),

    # -------------------------------------------------
    # stimulus onset
    # -------------------------------------------------

    stim_onset_idx=0,

    # -------------------------------------------------
    # dilation window
    # -------------------------------------------------

    dilation_window_ms=300,

    # -------------------------------------------------
    # onset detection
    # -------------------------------------------------

    onset_method="wilcoxon",

    # -------------------------------------------------
    # plotting
    # -------------------------------------------------

    plot=True,

    # -------------------------------------------------
    # CSV output
    # -------------------------------------------------

    save_csv=True,

    csv_filename="real_dataset_output.csv"
)


# =====================================================
# ---------------- RESULTS ----------------------------
# =====================================================

print("\n========================================")
print("FEATURE HEAD")
print("========================================\n")

print(

    results["features"].head()
)


# =====================================================
# ---------------- SUCCESS RATE -----------------------
# =====================================================

print("\n========================================")
print("SUCCESS RATE")
print("========================================\n")

print(

    f"Successful trials : "
    f"{len(results['success_trials'])}"
)

print(

    f"Failed trials     : "
    f"{len(results['failed_trials'])}"
)